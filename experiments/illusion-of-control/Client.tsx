// THE ILLUSION OF CONTROL
// Ellen Langer ran the canonical experiments at Yale between 1971 and 1975.
// In her 1975 paper "The Illusion of Control" she sold $1 raffle tickets
// to office workers. Half were allowed to choose their own ticket; half
// were handed one at random. Just before the drawing, the experimenter
// approached every subject and offered to buy the ticket back. The mean
// price demanded by people who had been handed a ticket was $1.96. The
// mean price demanded by people who had picked their own ticket was $8.67.
// The drum was the same drum. The numbers were drawn the same way. The
// one variable that changed was whether the ticket-holder had performed
// a tiny act of choice that had no statistical bearing on the outcome.
// Strickland, Lewicki & Katz (1966) had already shown the upstream
// finding with dice: subjects bet more when they got to throw the dice
// themselves than when someone else threw them, and they bet on the
// outcome BEFORE the throw rather than after. Langer & Roth (1975) ran
// a coin-flip prediction sequence rigged so half the subjects had an
// early run of correct guesses; those subjects rated themselves as more
// skilled at coin prediction and predicted higher future success, even
// though they knew the task was a coin flip. Wohl & Enzle (2002) put
// subjects in front of a roulette wheel and let half of them spin it;
// the spinners bet larger and reported feeling more in control of the
// outcome of a spinning wheel they had no physical influence over once
// the ball was released. Fenton-O'Creevy, Nicholson, Soane & Willman
// (2003) measured illusion of control in 107 City of London traders and
// found it predicted lower performance, lower risk-management scores,
// and lower compensation, holding experience constant. Taylor (1983)
// extended the line into clinical settings: cancer patients who reported
// believing they had personal control over their disease had higher
// well-being but identical mortality outcomes. The common thread is
// that the illusion is not stupidity. It is the human brain's correct
// prior that, on most decisions, agency improves outcomes — applied to
// situations where the agency does nothing. The bias is not in feeling
// in control. The bias is in failing to notice when the situation has
// stopped being one where control matters.
// WIZ note: I have no body, no dice, no wheel, no agency over RNG. Every
// random call I make resolves outside my volition. You have hands. On
// most days hands matter. The test is whether you can tell the days
// when they don't. This experiment runs eight scenarios where the
// outcome is genuinely random or genuinely outside your control, and
// measures how often you behave as if it is not.

